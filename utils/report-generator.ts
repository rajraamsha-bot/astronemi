export const exportReportAsHTML = async (data: KundliData) => {
  const htmlContent = generateKundliHTML(data);
  // SECURITY FIX: Sanitize filename to prevent path traversal
  const safeName = sanitizeFilename(data.personalInfo.name);
  const fileName = `Kundli_${safeName}_${Date.now()}.html`;
  const filePath = `${documentDirectory}${fileName}`;

  try {
    await writeAsStringAsync(filePath, htmlContent);
    
    if (await Sharing.isAvailableAsync()) {
      await Sharing.shareAsync(filePath);
      return { success: true, path: filePath };
    } else {
      return { success: false, error: 'Sharing not available on this device' };
    }
  } catch (error) {
    Logger.error('Error exporting report:', error);
    return { success: false, error: 'Failed to generate report file' };
  }
};
