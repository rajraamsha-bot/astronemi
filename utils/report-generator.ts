/**
 * Report Generator Utility
 * Generates high-fidelity HTML reports for astrological data
 * which can be shared or printed as PDF by the user.
 */

/**
 * SECURITY: Escape HTML to prevent XSS injection
 */
function escapeHtml(unsafe: string): string {
  if (typeof unsafe !== 'string') return '';
  return unsafe
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#039;');
}

/**
 * SECURITY: Sanitize filename to prevent path traversal
 * Only allows alphanumeric characters, hyphens, and underscores
 */
function sanitizeFilename(name: string): string {
  if (typeof name !== 'string' || name.length === 0) {
    return 'Kundli_Report';
  }
  // Remove any characters that aren't alphanumeric, space, hyphen, or underscore
  // Then replace spaces with underscores
  return name
    .replace(/[^a-zA-Z0-9\s\-_]/g, '')
    .replace(/\s+/g, '_')
    .slice(0, 50) || 'Kundli_Report'; // Limit length and provide fallback
}

