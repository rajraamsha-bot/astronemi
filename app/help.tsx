export default function HelpScreen() {
  const [expandedFAQ, setExpandedFAQ] = useState<string | null>(null);
  const [selectedCategory, setSelectedCategory] = useState<string>('all');
  const [message, setMessage] = useState('');
  const [email, setEmail] = useState('');

  const { t } = useLanguage();

  const categories = ['all', 'Kundli', 'Consultations', 'Payments', 'Account', 'Technical'];

  const filteredFAQs = selectedCategory === 'all' 
    ? faqs 
    : faqs.filter(faq => faq.category === selectedCategory);

  const handleContact = (type: 'chat' | 'call' | 'email') => {
    switch (type) {
      case 'chat':
        Alert.alert(t('help.liveChat'), t('help.liveChatMsg'));
        break;
      case 'call': {
        const href = supportTelHref();
        if (href) Linking.openURL(href);
        else Alert.alert(t('help.callUs'), t('help.contactNotConfigured'));
        break;
      }
      case 'email': {
        const href = supportMailHref();
        if (href) Linking.openURL(href);
        else Alert.alert(t('help.email'), t('help.contactNotConfigured'));
        break;
      }
    }
  };

  const handleSubmitQuery = () => {
    if (!message.trim()) {
      Alert.alert(t('common.error'), t('help.enterQuery'));
      return;
    }
    Alert.alert(t('common.success'), t('help.querySubmitted'));
    setMessage('');
    setEmail('');
  };

  return (
    <SafeAreaView style={styles.container} edges={['top']}>
      <View style={styles.header}>
        <TouchableOpacity
          style={styles.backButton}
          onPress={() => router.back()}
        >
          <ArrowLeft color={Colors.text} size={24} />
        </TouchableOpacity>
        <Text style={styles.headerTitle}>{t('profile.help')}</Text>
        <View style={{ width: 40 }} />
      </View>

      <ScrollView style={styles.content} showsVerticalScrollIndicator={false}>
        {/* Contact Options */}
        <View style={styles.contactSection}>
          <Text style={styles.sectionTitle}>{t('profile.contactUs')}</Text>
          <View style={styles.contactGrid}>
            <TouchableOpacity 
              style={styles.contactCard}
              onPress={() => handleContact('chat')}
            >
              <LinearGradient
                colors={['#4CAF50', '#45a049']}
                style={styles.contactIconContainer}
              >
                <MessageCircle color="#FFF" size={24} />
              </LinearGradient>
              <Text style={styles.contactLabel}>{t('help.liveChat')}</Text>
              <Text style={styles.contactSubtext}>{t('help.available247')}</Text>
            </TouchableOpacity>

            <TouchableOpacity 
              style={styles.contactCard}
              onPress={() => handleContact('call')}
            >
              <LinearGradient
                colors={['#2196F3', '#1976D2']}
                style={styles.contactIconContainer}
              >
                <Phone color="#FFF" size={24} />
              </LinearGradient>
              <Text style={styles.contactLabel}>{t('help.callUs')}</Text>
              <Text style={styles.contactSubtext}>{SUPPORT_PHONE || t('help.contactNotConfigured')}</Text>
            </TouchableOpacity>

            <TouchableOpacity 
              style={styles.contactCard}
              onPress={() => handleContact('email')}
            >
              <LinearGradient
                colors={['#FF9800', '#F57C00']}
                style={styles.contactIconContainer}
              >
                <Mail color="#FFF" size={24} />
              </LinearGradient>
              <Text style={styles.contactLabel}>{t('help.email')}</Text>
              <Text style={styles.contactSubtext}>{SUPPORT_EMAIL || t('help.contactNotConfigured')}</Text>
            </TouchableOpacity>
          </View>
        </View>

        {/* Quick Links */}
        <View style={styles.quickLinksSection}>
          <TouchableOpacity 
            style={styles.quickLinkItem}
            onPress={() => router.push('/privacy-policy')}
          >
            <Shield size={20} color={Colors.primary} />
            <Text style={styles.quickLinkText}>{t('settings.privacyPolicy')}</Text>
            <ChevronDown size={20} color={Colors.textLight} style={{ transform: [{ rotate: '-90deg' }] }} />
          </TouchableOpacity>
          <TouchableOpacity 
            style={styles.quickLinkItem}
            onPress={() => router.push('/terms')}
          >
            <FileText size={20} color={Colors.primary} />
            <Text style={styles.quickLinkText}>{t('settings.terms')}</Text>
            <ChevronDown size={20} color={Colors.textLight} style={{ transform: [{ rotate: '-90deg' }] }} />
          </TouchableOpacity>
          <TouchableOpacity 
            style={styles.quickLinkItem}
            onPress={() => router.push('/about')}
          >
            <HelpCircle size={20} color={Colors.primary} />
            <Text style={styles.quickLinkText}>{t('settings.about')}</Text>
            <ChevronDown size={20} color={Colors.textLight} style={{ transform: [{ rotate: '-90deg' }] }} />
          </TouchableOpacity>
        </View>

        {/* FAQs */}
        <View style={styles.faqSection}>
          <Text style={styles.sectionTitle}>{t('help.faq')}</Text>
          
          {/* Category Filter */}
          <ScrollView 
            horizontal 
            showsHorizontalScrollIndicator={false}
            style={styles.categoryScroll}
          >
            {categories.map((cat) => (
              <TouchableOpacity
                key={cat}
                style={[
                  styles.categoryChip,
                  selectedCategory === cat && styles.categoryChipActive,
                ]}
                onPress={() => setSelectedCategory(cat)}
              >
                <Text style={[
                  styles.categoryChipText,
                  selectedCategory === cat && styles.categoryChipTextActive,
                ]}>
                  {cat === 'all' ? t('help.all') : cat}
                </Text>
              </TouchableOpacity>
            ))}
          </ScrollView>

          {/* FAQ List */}
          {filteredFAQs.map((faq, index) => (
            <TouchableOpacity
              key={index}
              style={styles.faqItem}
              onPress={() => setExpandedFAQ(expandedFAQ === `${index}` ? null : `${index}`)}
            >
              <View style={styles.faqHeader}>
                <Text style={styles.faqQuestion}>{t(`help.faq${faqs.indexOf(faq)}Q`)}</Text>
                {expandedFAQ === `${index}` ? (
                  <ChevronUp size={20} color={Colors.textLight} />
                ) : (
                  <ChevronDown size={20} color={Colors.textLight} />
                )}
              </View>
              {expandedFAQ === `${index}` && (
                <Text style={styles.faqAnswer}>{t(`help.faq${faqs.indexOf(faq)}A`)}</Text>
              )}
            </TouchableOpacity>
          ))}
        </View>

        {/* Submit Query */}
        <View style={styles.querySection}>
          <Text style={styles.sectionTitle}>{t('help.submitQuery')}</Text>
          <View style={styles.queryForm}>
            <TextInput
              style={styles.emailInput}
              placeholder={t('help.emailPlaceholder')}
              placeholderTextColor={Colors.textLight}
              value={email}
              onChangeText={setEmail}
              keyboardType="email-address"
              autoCapitalize="none"
            />
            <TextInput
              style={styles.messageInput}
              placeholder={t('help.messagePlaceholder')}
              placeholderTextColor={Colors.textLight}
              value={message}
              onChangeText={setMessage}
              multiline
              numberOfLines={4}
              textAlignVertical="top"
            />
            <TouchableOpacity
              style={styles.submitButton}
              onPress={handleSubmitQuery}
            >
              <Send size={18} color="#FFF" />
              <Text style={styles.submitButtonText}>{t('help.submitQueryButton')}</Text>
            </TouchableOpacity>
          </View>
        </View>

        {/* Support Info */}
        <View style={styles.supportInfo}>
          <View style={styles.supportInfoItem}>
            <Clock size={16} color={Colors.textLight} />
              <Text style={styles.supportInfoText}>
                {t('help.responseTime')}
              </Text>
          </View>
          <View style={styles.supportInfoItem}>
            <MapPin size={16} color={Colors.textLight} />
            <Text style={styles.supportInfoText}>
              AstroNemi Technologies Pvt. Ltd.
            </Text>
          </View>
        </View>

        <View style={{ height: 100 }} />
      </ScrollView>
    </SafeAreaView>
  );
}

