// Module-scoped QueryClient shared by AppProviders and AuthContext.
// Kept in its own module so AuthContext can clear the cache on logout
// without importing AppProviders (which would be a cycle: AppProviders
// mounts AuthProvider).
import { Platform } from 'react-native';
import { QueryClient } from '@tanstack/react-query';

export const queryClient = new QueryClient({
  defaultOptions: {
    queries: {
      staleTime: 5 * 60 * 1000,
      gcTime: 24 * 60 * 60 * 1000,
      retry: 2,
      retryDelay: (attemptIndex) => Math.min(1000 * 2 ** attemptIndex, 10000),
      refetchOnWindowFocus: Platform.OS === 'web',
      refetchOnReconnect: true,
      refetchOnMount: true,
    },
    mutations: {
      retry: 1,
      retryDelay: 1000,
    },
  },
});
